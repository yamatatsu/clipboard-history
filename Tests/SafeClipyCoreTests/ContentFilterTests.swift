import Testing
@testable import SafeClipyCore

@Suite struct ContentFilterTests {
    func evaluate(_ text: String, types: [String] = ["public.utf8-plain-text"], app: String? = "com.apple.TextEdit") -> ContentFilter.Decision {
        ContentFilter.evaluate(text: text, pasteboardTypes: types, frontmostBundleID: app)
    }

    @Test func recordsPlainText() {
        #expect(evaluate("hello world") == .record)
        #expect(evaluate("日本語のテキスト") == .record)
    }

    @Test(arguments: [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ])
    func skipsConcealedMarkers(type: String) {
        #expect(evaluate("secret", types: ["public.utf8-plain-text", type]) == .skip(.marker))
    }

    @Test func skipsExcludedApps() {
        #expect(evaluate("secret", app: "com.1password.1password") == .skip(.excludedApp))
        #expect(evaluate("secret", app: "com.apple.Passwords") == .skip(.excludedApp))
        #expect(evaluate("text", app: nil) == .record)
    }

    @Test func skipsEmptyAndHuge() {
        #expect(evaluate("") == .skip(.empty))
        #expect(evaluate(" \n\t ") == .skip(.empty))
        #expect(evaluate(String(repeating: "a", count: Config.maxTextBytes + 1)) == .skip(.tooLarge))
        #expect(evaluate(String(repeating: "a", count: Config.maxTextBytes)) == .record)
    }

    // テスト用の値は実在しないダミー。
    @Test(arguments: [
        "-----BEGIN OPENSSH PRIVATE KEY-----\nabc",
        "-----BEGIN RSA PRIVATE KEY-----",
        "token: ghp_" + String(repeating: "a", count: 36),
        "github_pat_" + String(repeating: "B", count: 22),
        "AKIA" + String(repeating: "Z", count: 16),
        "key=ASIA" + String(repeating: "1", count: 16) + " end",
        "xoxb-1234567890-abcdef",
        "sk-ant-" + String(repeating: "x", count: 20),
        "sk-" + String(repeating: "y", count: 20),
        "AIza" + String(repeating: "c", count: 35),
        "eyJhbGciOiJIUzI1.eyJzdWIiOiIxMjM0.SflKxwRJSMeKKF2QT4",
    ])
    func skipsSensitivePatterns(text: String) {
        #expect(evaluate(text) == .skip(.sensitivePattern))
    }

    @Test(arguments: [
        "ghp_short",
        "AKIA123",
        "ask-me-anything",
        "sk-short",
        "-----BEGIN CERTIFICATE-----",
        "eyJ only",
        "https://example.com/path?q=1",
    ])
    func recordsLookalikes(text: String) {
        #expect(evaluate(text) == .record)
    }
}
